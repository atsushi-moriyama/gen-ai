# MAGIC %md
# MAGIC ### E1. データセット構成の原則
# MAGIC
# MAGIC 評価の質は、データセットに大きく左右されます。適切に設計された評価用データセットは、代表性があり、多様性に富み、適切なグラウンドトゥルースを含んでいる必要があります。
# MAGIC
# MAGIC **データセット構成の原則：**
# MAGIC
# MAGIC **1. 代表性**：典型的なユーザークエリと使用ケースを反映する例を含めます
# MAGIC - 本番環境ログやユーザー調査を分析して一般的なパターンを特定します
# MAGIC - クエリタイプの分布が期待される使用状況と一致することを確認します
# MAGIC - 様々なクエリの複雑さレベルを含めます
# MAGIC
# MAGIC **2. エッジケースのカバレッジ**：境界条件と潜在的な失敗を意図的にテストします
# MAGIC - 複数の方法で解釈できる曖昧なクエリ
# MAGIC - 検索コーパスで利用できない情報を必要とするクエリ
# MAGIC - 失敗モードをトリガーするように設計された敵対的例
# MAGIC - 予期しない形式や表現のクエリ

# COMMAND ----------

# MAGIC %md
# MAGIC ### E2. 多様性とグラウンドトゥルースの手法
# MAGIC
# MAGIC **3. 多様性の次元**：入力の複数の側面を変化させます
# MAGIC - クエリの長さ（簡潔 vs. 冗長）
# MAGIC - クエリの複雑さ（単純な事実検索 vs. 多段階推論）
# MAGIC - ドメインカバレッジ（エージェントが処理すべき異なるトピック）
# MAGIC - ユーザーの専門知識レベル（初心者 vs. 専門家のドメイン知識）
# MAGIC
# MAGIC **グラウンドトゥルースの手法：**
# MAGIC
# MAGIC **専門家ラベリング**：ドメインエキスパートが期待される出力や事実セットを作成します
# MAGIC - 最も正確ですがリソース集約的です
# MAGIC - 高リスクアプリケーションには不可欠です
# MAGIC - 再利用可能なゴールドスタンダードデータセットを作成します
# MAGIC
# MAGIC **合成生成**：LLMを使用して期待される応答を生成します
# MAGIC - スケーラブルですが検証が必要です
# MAGIC - 評価のブートストラップに有用です
# MAGIC - 人間によるスポットチェックが必要です
# MAGIC
# MAGIC **本番環境マイニング**：推論テーブルから例を抽出します
# MAGIC - 実際の使用パターンを反映します
# MAGIC - フィルタリングやクリーニングが必要な場合があります
# MAGIC - 新たな失敗モードを特定できます

