# MAGIC ### C1. 実世界のパフォーマンス分析
# MAGIC
# MAGIC オンライン評価は、本番環境での実際のユーザーインタラクションを使用してエージェントのパフォーマンスを分析します。このアプローチは、実際の使用パターン、予期しない入力、多様なユーザー層でのエージェントのパフォーマンスを捉えます。
# MAGIC
# MAGIC **オンライン評価の特徴：**
# MAGIC
# MAGIC - **実世界のデータ**：実際のユーザークエリと行動に対して評価します
# MAGIC - **スケール検証**：エージェントが本番環境の負荷とリクエストの多様性をどのように処理するかをテストします
# MAGIC - **ドリフト検出**：時間の経過に伴うパフォーマンスの劣化を特定します
# MAGIC - **継続的モニタリング**：一回限りの評価ではなく継続的な品質シグナルを提供します
# MAGIC - **ユーザーフィードバックの統合**：自動評価と実際のユーザー満足度を組み合わせます

# COMMAND ----------

# MAGIC %md
# MAGIC ### C2. オンライン評価ワークフロー
# MAGIC
# MAGIC **オンライン評価ワークフロー：**
# MAGIC
# MAGIC 1. **推論ログ**：AI Gatewayで強化された推論テーブルを有効にしてエージェントをデプロイします
# MAGIC 2. **自動トレース**：すべての本番環境リクエストが推論テーブルにキャプチャされたトレースを作成します
# MAGIC 3. **スケジュール評価**：最近の本番環境トレースに対して定期的にスコアラーを実行します
# MAGIC 4. **アラート設定**：品質劣化に対するモニタリングアラートを設定します
# MAGIC 5. **フィードバック収集**：ユーザーのサムズアップ/サムズダウンや明示的なフィードバックを収集します
# MAGIC 6. **データセット拡張**：オフライン評価のために興味深い本番環境の例を抽出します

