# MAGIC %md
# MAGIC ### F1. 評価のためのガバナンス層
# MAGIC
# MAGIC Unity Catalogは、評価ワークフローのガバナンス層を提供し、トレーサビリティ、アクセス制御、リネージ追跡を確保します。
# MAGIC
# MAGIC **エージェント登録**：Unity Catalogにエージェントを登録すると：
# MAGIC - すべてのエージェントの依存関係（vectorインデックス、UC関数、モデルエンドポイント）が追跡されます
# MAGIC - アクセス制御により、誰がエージェントを評価または変更できるかが決定されます
# MAGIC - リネージは、どの評価データセットとメトリクスが各バージョンを生成したかを示します
# MAGIC - エイリアス（`@champion` など）により、クリーンなプロモーションワークフローが可能になります

# COMMAND ----------

# MAGIC %md
# MAGIC ### F2. データセットとトレースストレージ
# MAGIC
# MAGIC **評価データセットストレージ**：データセットをDeltaテーブルまたはボリュームとして保存します：
# MAGIC - エージェントバージョンと並行してデータセットをバージョン管理します
# MAGIC - 機密評価データにアクセス制御を適用します
# MAGIC - SQLベースのデータセット分析と拡張を可能にします
# MAGIC - 協調的なデータセットキュレーションをサポートします
# MAGIC
# MAGIC **トレースストレージ**：MLflowトレースはUnity Catalogに保存されます：
# MAGIC - 分析のためにSQLを使用してトレースをクエリします
# MAGIC - より深い洞察のためにトレースと評価結果を結合します
# MAGIC - 本番環境トレースデータにデータガバナンスポリシーを適用します
# MAGIC - （必要に応じて）チーム間のトレース共有を有効にする
# MAGIC
# MAGIC この統合により、評価インフラストラクチャがデータプラットフォームの他の部分と同じガバナンス、セキュリティ、コラボレーション機能の恩恵を受けることが保証されます。

