# COMMAND ----------

# MAGIC %md
# MAGIC ## A. プロンプトエンジニアリングの基礎
# MAGIC
# MAGIC 複雑なAIアーキテクチャを構築する前に、まず相互作用の基本単位であるプロンプトを習得する必要があります。このセクションでは、モデルの動作を導くための指示を作成する技術を探求し、統計的予測と真の推論能力を区別します。しかし、プロンプトを洗練していく中で、モデルが訓練データのみに基づいて知ることができる内容の厳しい境界に必然的に遭遇します。

# COMMAND ----------

# MAGIC %md
# MAGIC ### A1. プロンプトエンジニアリングの定義
# MAGIC
# MAGIC プロンプトエンジニアリングは、大規模言語モデル（LLM）によって生成される出力を最適化するために、入力テキスト（プロンプト）を改良する実践です。これは指示レイヤーに焦点を当てた **戦術的** な分野です。**Few-Shot Prompting**（例の提供）や **Persona Adoption**（役割の割り当て）などの技術を使用して、モデルの動作と形式を導きます。理想的には、プロンプトエンジニアリングはモデルを推論エンジンとして扱い、事前訓練された重みを活用して問題を効果的に解決するよう導きます。

# COMMAND ----------

# MAGIC %md
# MAGIC ### A2. 推論モデルと非推論モデル
# MAGIC
# MAGIC 効果的なプロンプティングには、基盤となるモデルの能力を理解することが必要です。主要な2つのカテゴリを検討しましょう：
# MAGIC
# MAGIC - **Non-Reasoning Models (e.g., Llama 3, GPT-4o)：** これらのモデルは統計的尤度に基づいて次のトークンを予測します。複雑な論理を分解し、誤った結論に急ぐことを避けるために、**Chain of Thought (CoT)** プロンプティング（「段階的に考えてください」）などの明示的な指導が必要です。
# MAGIC
# MAGIC - **Reasoning Models (e.g., OpenAI o1)：** これらのモデルは最終回答を生成する前に独自の内部思考の連鎖を生成するよう訓練されています。これらのモデルでは、手動のCoTプロンプティングはしばしば冗長または逆効果です。推論モデルのコンテキストエンジニアリングは、*思考プロセス* ではなく *目標* と *制約* の定義に焦点を当てます。

# COMMAND ----------

# MAGIC %md
# MAGIC ### A3. プロンプティングの境界
# MAGIC
# MAGIC プロンプトエンジニアリングには厳しい境界があります。どれほど指示を改良しても、モデルの訓練データに固有の以下の制限を克服することはできません：
# MAGIC
# MAGIC 1. **The Knowledge Cutoff：** モデルは、その訓練データのカットオフ日以降に発生した出来事について答えることができません。
# MAGIC    - *プロンプト例：* `2025年のノーベル物理学賞を受賞したのは誰ですか？`
# MAGIC
# MAGIC 1. **Hallucination：** 外部参照なしに特定の事実を求められた場合、モデルはしばしば真実よりも妥当性を優先し、引用やデータポイントを捏造します。
# MAGIC    - *プロンプト例：* `アボカドが血糖値を下げることを証明する科学的参考文献を見つけてください`
# MAGIC
# MAGIC 1. **Ambiguity：** プライベートなコンテキストがなければ、モデルは一般的な解釈にデフォルトします。
# MAGIC    - *プロンプト例：* `Lakehouseを保護する方法を説明してください。`（これはDatabricksデータレイクハウスガバナンスではなく、物理的な家のセキュリティに関するアドバイスを引き起こします。）

# COMMAND ----------

# MAGIC %md
# MAGIC ## B. 検索拡張生成（RAG）
# MAGIC
# MAGIC プロンプトエンジニアリングがモデルの応答 *方法* を最適化する一方で、モデルが *何を* 知っているかという根本的な問題に対処することはできません。固定された訓練データと幻覚の制限を克服するために、内部記憶に依存することから外部コンテキストを活用することへとアーキテクチャアプローチを転換する必要があります。このセクションでは、モデルの事前訓練された知識と独自データの間のギャップを埋める重要なframeworkである検索拡張生成（RAG）を紹介します。
# MAGIC
# MAGIC **RAG vs. Retrieval Agent：** 
# MAGIC RAGは、特定のツールやエージェントロジックに依存しない、検索と生成を結合するアーキテクチャパターンを指します。対照的に、**Retrieval agents** は、このパターンを運用化する具体的な実装であり、実際のシステム内でクエリルーティング、検索オーケストレーション、コンテキスト組み立てを処理します。

# COMMAND ----------

# MAGIC %md
# MAGIC ### B1. RAGの定義
# MAGIC
# MAGIC 先ほど定義した知識の境界を解決するために、記憶ベースのアプローチから **Retrieval Augmented Generation (RAG)** として知られるコンテキストベースのアーキテクチャに移行します。RAGは独自またはリアルタイムデータをプロンプトに注入し、モデルが内部記憶ではなく提供された事実に基づいて応答できるようにします。
# MAGIC
# MAGIC RAGプロセスは3つの主要段階で構成されます：
# MAGIC
# MAGIC - **Retrieval：** システムが知識ベース（**Mosaic AI Vector Search** でインデックス化）から関連するデータチャンクを検索します
# MAGIC - **Augmentation：** システムがこれらのチャンクをコンテキストウィンドウに注入します
# MAGIC - **Generation：** モデルが注入されたデータ *のみ* を使用して回答を合成します

# COMMAND ----------

# MAGIC %md
# MAGIC ### B2. コンテキストの課題
# MAGIC
# MAGIC RAGは知識のギャップを解決する一方で、新たな課題を導入します： **Context Rot**。初期のRAG実装は、開発者が大量のドキュメントを検索してプロンプトに貼り付けるだけだったため、しばしば失敗しました。このアプローチはモデルを圧倒し、以下の問題を引き起こします：
# MAGIC
# MAGIC - **Context Poisoning：** モデルを混乱させる無関係または矛盾する情報の含有
# MAGIC - **Lost in the Middle：** 長いコンテキストウィンドウの中間に埋もれた情報を無視し、最初または最後のデータを優先するモデルの傾向
# MAGIC
# MAGIC これらの課題は、次のセクションで探求する戦略的コンテキスト管理の必要性を浮き彫りにします。

# COMMAND ----------

# MAGIC %md
# MAGIC ## C. コンテキストエンジニアリングの原則
# MAGIC
# MAGIC 単にデータを検索するだけでは十分ではありません。生の情報をプロンプトに投入することは、しばしば明確性ではなく混乱を招きます。基本的なRAGから本番グレードのシステムに移行する際、コンテキストウィンドウを受動的なコンテナではなく、モデルの動作を積極的に形成する工学的環境として扱う必要があります。このセクションでは、信頼性と正確性を確保するために情報を構造化、フィルタリング、グラウンディングする方法を強調し、コンテキストエンジニアリングの原則を概説します。

# COMMAND ----------

# MAGIC %md
# MAGIC ### C1. コンテキスト環境の定義
# MAGIC
# MAGIC **Context Engineering**は、入力ウィンドウ全体の戦略的設計です。単一の指示を書くことを超えて、完全なシステム状態の管理に移行します。**System Instructions**、**Conversation History**、**Retrieved Data**、**User Constraints** の相互作用を調整して、モデルがタスクを効果的に実行するために必要な信号を正確に持つようにします。

# COMMAND ----------

# MAGIC %md
# MAGIC ### C2. システムプロンプトの設計
# MAGIC
# MAGIC コンテキストエンジニアリングパラダイムでは、システムプロンプトは単なる要求ではなく、モデルがどのように動作すべきかを定義する動作プログラムです。
# MAGIC
# MAGIC 効果的なシステムプロンプトの主要コンポーネントには以下が含まれます：
# MAGIC
# MAGIC - **Role Definition：** ペルソナを明示的に定義する（例：「あなたはDatabricksセキュリティアーキテクトです」）
# MAGIC - **Negative Constraints：** モデルが *できない* ことを定義する（例：「競合製品について言及しないでください」または「明示的に要求されない限りコードを提供しないでください」）
# MAGIC - **Output Formatting：** 構造化出力（例：JSON、YAML、マークダウンテーブル）を強制して、下流アプリケーションが応答を確定的に解析できるようにする

# COMMAND ----------

# MAGIC %md
# MAGIC ### C3. 厳密なグラウンディングとチャンキング
# MAGIC
# MAGIC 検索は幻覚を防ぎ、正確性を確保するために厳密に管理される必要があります。
# MAGIC
# MAGIC 主要戦略には以下が含まれます：
# MAGIC
# MAGIC - **Grounding Instructions：** モデルを検索されたコンテキストに結び付ける明示的な指示を使用します。例：*「提供されたコンテキストチャンクのみを使用して回答してください。回答が存在しない場合は、『その情報は持っていません』と述べてください。」*
# MAGIC - **Metadata Filtering：** **Unity Catalog** メタデータを利用して、モデルに到達する *前に* 検索をフィルタリングします。例えば、ユーザーが「2024年の収益」について尋ねた場合、システムは`year=2024`のチャンクをフィルタリングして、モデルが古い2023年のデータを見ることを防ぐ必要があります

# COMMAND ----------

# MAGIC %md
# MAGIC ### C4. マルチターン状態の管理
# MAGIC
# MAGIC 長い会話（エージェントなど）を含むアプリケーションでは、コンテキストウィンドウは最終的に満杯になります。コンテキストエンジニアリングでは、この状態を管理するための戦略的アプローチが必要です：
# MAGIC
# MAGIC - **Summarization：** 会話履歴を主要な決定と事実の要約に定期的に圧縮する
# MAGIC - **Moving Window：** 新しい検索のためのトークンスペースを確保するために、最も古いメッセージを破棄する
# MAGIC - **Selective Persistence：** どの情報（例：ユーザー名、現在のプロジェクトID）がコンテキストに永続的に残る必要があるか、何を破棄できるかを決定する
# MAGIC
# MAGIC これらの戦略により、トークン制限内に留まりながら関連するコンテキストを維持することが保証されます。

# COMMAND ----------

# MAGIC %md
# MAGIC ## D. コンテキスト制約：トークン予算とウィンドウ制限
# MAGIC
# MAGIC 最も優雅に工学的に設計されたコンテキストでも、コンピューティングリソースとモデルアーキテクチャの厳しい制約を受けます。アプリケーションをスケールする際、包括的なコンテキストへの欲求と、トークン制限、レイテンシ、運用コストの現実とのバランスを取る必要があります。このセクションでは、コンテキストウィンドウの経済性を検討し、応答品質を犠牲にすることなくトークン予算を最適化する戦略を提供します。

# COMMAND ----------

# MAGIC %md
# MAGIC ### D1. コンテキストウィンドウの理解
# MAGIC
# MAGIC すべてのモデルには **Context Window Limit**（例：8k、32k、または128kトークン）があります。これは、モデルが利用できる作業メモリの厳しい制限を表します。
# MAGIC
# MAGIC コンテキストウィンドウは以下で構成されます：
# MAGIC
# MAGIC - **Input Tokens：** モデルに送信するテキスト（指示 + 検索ドキュメント + 履歴）
# MAGIC - **Output Tokens：** モデルが生成するテキスト
# MAGIC
# MAGIC **The Trade-off：** より多くの検索データでウィンドウを満たすにつれて、モデルの推論能力は劣化し（「中間での迷子」現象）、レイテンシが大幅に増加します。パフォーマンスを維持するためには、戦略的コンテキスト管理が不可欠です。

# COMMAND ----------

# MAGIC %md
# MAGIC ### D2. トークン経済学と最適化
# MAGIC
# MAGIC コンテキストは無料ではありません。**Databricks Foundation Model APIs**（および他のプロバイダー）は、消費される入力および出力トークンの量に基づいて課金します。
# MAGIC
# MAGIC 主要な考慮事項：
# MAGIC
# MAGIC - **Cost Management：** すべてのクエリに対して50のドキュメントを検索する素朴なRAGシステムは、トークン予算を急速に消費します
# MAGIC
# MAGIC **Optimization Strategies：**
# MAGIC
# MAGIC - **Just-in-Time Retrieval：** チャットの開始時に完全なマニュアルを読み込む代わりに、ユーザーが関連する質問をした時にのみ特定のセクションを検索するツールをエージェントに提供する
# MAGIC - **Reranking：** リランカーモデルを使用して検索された上位50チャンクをスコア化し、最も関連性の高い上位3-5チャンクのみを最終的なコンテキストウィンドウに注入する
# MAGIC
# MAGIC これらの戦略により、包括的なコンテキストとコスト効率およびパフォーマンスのバランスを取ることができます。

